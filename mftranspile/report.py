"""Translation report (markdown)."""
from __future__ import annotations

from pathlib import Path

from mftranspile.translate import TranslationResult


def build_report(result: TranslationResult, cobol_path: str, jcl_steps: list[dict],
                 job_name: str) -> str:
    lines = [
        f"# Translation Report — {result.program_id}",
        "",
        f"- Source: `{cobol_path}`",
        f"- Generated by: `mftranspile`",
        "",
        "## Summary",
        "",
    ]
    for n in result.notes:
        lines.append(f"- {n}")
    auto = sum(1 for r in result.report_rows if r["confidence"] == "AUTO")
    pattern = sum(1 for r in result.report_rows if r["confidence"] == "PATTERN")
    lines += [
        f"- Statements mapped: {len(result.report_rows)} "
        f"({auto} AUTO, {pattern} PATTERN)",
        "",
        "## Statement mapping",
        "",
        "| COBOL construct | COBOL | Generated PySpark | Confidence |",
        "|---|---|---|---|",
    ]
    for r in result.report_rows:
        lines.append(f"| {r['construct']} | `{r['cobol']}` | {r['spark']} | **{r['confidence']}** |")

    lines += [
        "",
        "> Confidence: **AUTO** = directly translated; **PATTERN** = recognized a "
        "common archetype (review the generated expression); **REVIEW** = needs a human.",
        "",
        "## JCL -> Workflow tasks",
        "",
        f"Job: **{job_name}**",
        "",
        "| JCL step | Program | Databricks task |",
        "|---|---|---|",
    ]
    for s in jcl_steps:
        lines.append(f"| {s.get('step','')} | {s.get('pgm','')} | `{s.get('pgm','').lower()}` |")

    lines += [
        "",
        "## Generated schema",
        "",
        "```python",
        result.schema_source.strip(),
        "```",
        "",
        "## Generated module",
        "",
        "```python",
        result.module_source.strip(),
        "```",
    ]
    return "\n".join(lines)
